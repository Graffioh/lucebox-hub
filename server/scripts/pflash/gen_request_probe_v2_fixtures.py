#!/usr/bin/env python3
"""Generate test/pflash/fixtures/request_probe_v2_parity.inc: replay-parity fixtures for the V2-A3 candidate rule against the
trainer's offline mirror rule.probe_query_v2 (luce_box lucebox_training/pflash, CANDIDATE_RULE
cand_v3_latest_human_prev8_plus_all_nonsystem_turns, V2-A5). Deterministic (seed 0).
  python3 gen_request_probe_v2_fixtures.py TRAINER_SRC_DIR OUT.inc"""
import argparse
import random
import sys

import numpy as np


def main():
    ap = argparse.ArgumentParser(description="Generate deterministic request-probe parity fixtures.")
    ap.add_argument("trainer_src_dir", help="Directory containing the trainer's pflash_scorer package")
    ap.add_argument("out", help="Output request_probe_v2_parity.inc")
    args = ap.parse_args()
    sys.path.insert(0, args.trainer_src_dir)
    from pflash_scorer.request_probe import contract  # noqa: E402
    from pflash_scorer.request_probe.rule import probe_query_v2  # noqa: E402

    assert contract.CANDIDATE_RULE == "cand_v3_latest_human_prev8_plus_all_nonsystem_turns"
    rng = random.Random(0)
    cases = []
    for case in range(80):
        roles = ["system"] if rng.random() < 0.7 else []
        n_msgs = rng.randint(1, 9)
        for _ in range(n_msgs):
            roles.append(rng.choice(["user", "user", "assistant", "tool", "tool"]))
        big = case % 8 == 0
        spans, pos = [], 0
        for r in roles:
            L = rng.randint(0, 900 if big else 60)
            spans.append((pos, pos + L))
            pos += L + rng.randint(1, 4)
        n = pos + 3
        hits = []
        lg = np.full(n, -1.0, np.float32)
        for b, e in spans:
            k = b
            while k < e:
                if rng.random() < (0.35 if big else 0.15):
                    L = rng.randint(1, 12 if not big else 400)
                    z = min(e, k + L)
                    hits.append((k, z))
                    lg[k:z] = 1.0
                    k = z + rng.randint(1, 5)
                else:
                    k += rng.randint(1, 8)
        q, _runs, info = probe_query_v2(lg, 0.0, list(zip(roles, spans)))
        qs = []
        for t in q:
            if qs and qs[-1][1] == t:
                qs[-1][1] = t + 1
            else:
                qs.append([t, t + 1])
        cases.append((roles, spans, n, hits, qs, info["candidates"]))

    with open(args.out, "w") as f:
        import hashlib
        import os
        src = os.path.join(args.trainer_src_dir, "pflash_scorer", "request_probe")
        shas = {n: hashlib.sha256(open(os.path.join(src, n), "rb").read()).hexdigest()[:16] for n in ("rule.py", "contract.py")}
        f.write("// Generated by server/scripts/pflash/gen_request_probe_v2_fixtures.py from the trainer's rule.probe_query_v2\n")
        f.write("// trainer sources: rule.py %s, contract.py %s\n" % (shas["rule.py"], shas["contract.py"]))
        f.write("// (luce_box v2 branch, CANDIDATE_RULE cand_v3_latest_human_prev8_plus_all_nonsystem_turns). Do not edit.\n")
        for i, (roles, spans, n, hits, qs, cands) in enumerate(cases):
            f.write("{%d, {%s}, {%s}, {%s}, {%s}, {%s}},\n" % (
                n, ", ".join('"%s"' % r for r in roles), ", ".join("{%d, %d}" % s for s in spans),
                ", ".join("{%d, %d}" % h for h in hits), ", ".join("{%d, %d}" % tuple(x) for x in qs),
                ", ".join(str(c) for c in cands)))
    print(args.out, len(cases), "cases")


if __name__ == "__main__":
    main()
